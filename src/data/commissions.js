export function isCommissionActive(commissionCode) {
  if (!commissionCode) return false;
  const match = commissions.find(c => c.code.toLowerCase() === commissionCode.toLowerCase());
  return match ? match.status === 'active' : false;
}

export function getActiveCommissions() {
  return commissions.filter(c => c.status === 'active');
}
